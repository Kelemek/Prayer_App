import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }

  for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separator = trimmed.indexOf("=");
    if (separator === -1) {
      continue;
    }

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

function escapeTsString(value) {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

loadDotEnv(path.join(root, ".env.production"));
loadDotEnv(path.join(root, ".env"));

const supabaseUrl = process.env.VITE_SUPABASE_URL ?? "";
const supabasePublishableKey = process.env.VITE_SUPABASE_PUBLISHABLE_KEY ?? "";
const appUrl = process.env.VITE_APP_URL ?? "";

const output = `// Generated by scripts/write-prod-environment.mjs — do not edit manually.
export const environment = {
  production: true,
  supabaseUrl: '${escapeTsString(supabaseUrl)}',
  supabasePublishableKey: '${escapeTsString(supabasePublishableKey)}',
  appUrl: '${escapeTsString(appUrl)}',
};
`;

const target = path.join(root, "src/environments/environment.prod.ts");
fs.writeFileSync(target, output);

if (!supabaseUrl || !supabasePublishableKey) {
  console.warn(
    "[write-prod-environment] Warning: VITE_SUPABASE_URL and/or VITE_SUPABASE_PUBLISHABLE_KEY are missing. " +
      "Set them in Vercel project settings or .env.production before building for production."
  );
}
