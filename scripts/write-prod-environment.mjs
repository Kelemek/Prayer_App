import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }

  for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separator = trimmed.indexOf("=");
    if (separator === -1) {
      continue;
    }

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

function escapeTsString(value) {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function parsePlatformHosts(raw) {
  if (!raw?.trim()) {
    return [];
  }
  return raw
    .split(",")
    .map((host) => host.trim().toLowerCase())
    .filter((host) => host.length > 0);
}

function normalizeCookieParentDomain(raw) {
  const trimmed = raw?.trim() ?? "";
  if (!trimmed) {
    return "";
  }
  return trimmed.startsWith(".") ? trimmed : `.${trimmed}`;
}

function normalizeTenantHostSuffix(raw) {
  return (raw?.trim() ?? "").toLowerCase().replace(/^\./, "");
}

function escapeTsStringArray(values) {
  return `[${values.map((v) => `'${escapeTsString(v)}'`).join(", ")}]`;
}

loadDotEnv(path.join(root, ".env.production"));
loadDotEnv(path.join(root, ".env"));

const supabaseUrl = process.env.VITE_SUPABASE_URL ?? "";
const supabasePublishableKey = process.env.VITE_SUPABASE_PUBLISHABLE_KEY ?? "";
const appUrl = process.env.VITE_APP_URL ?? "";
const platformHosts = parsePlatformHosts(process.env.VITE_PLATFORM_HOSTS);
const cookieParentDomain = normalizeCookieParentDomain(
  process.env.VITE_COOKIE_PARENT_DOMAIN
);
const tenantHostSuffix = normalizeTenantHostSuffix(
  process.env.VITE_TENANT_HOST_SUFFIX
);

const output = `// Generated by scripts/write-prod-environment.mjs — do not edit manually.
import type { AppEnvironment } from './environment.types';

export const environment: AppEnvironment = {
  production: true,
  supabaseUrl: '${escapeTsString(supabaseUrl)}',
  supabasePublishableKey: '${escapeTsString(supabasePublishableKey)}',
  appUrl: '${escapeTsString(appUrl)}',
  platformHosts: ${escapeTsStringArray(platformHosts)},
  cookieParentDomain: '${escapeTsString(cookieParentDomain)}',
  tenantHostSuffix: '${escapeTsString(tenantHostSuffix)}',
};
`;

const target = path.join(root, "src/environments/environment.prod.ts");
fs.writeFileSync(target, output);

if (!supabaseUrl || !supabasePublishableKey) {
  console.warn(
    "[write-prod-environment] Warning: VITE_SUPABASE_URL and/or VITE_SUPABASE_PUBLISHABLE_KEY are missing. " +
      "Set them in Vercel project settings or .env.production before building for production."
  );
}
